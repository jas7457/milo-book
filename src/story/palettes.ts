import * as THREE from 'three'
import type { Palette } from '../state'

const c1 = new THREE.Color()
const c2 = new THREE.Color()
const mixHex = (a: string, b: string, t: number) => '#' + c1.set(a).lerp(c2.set(b), t).getHexString()

export function mixPalette(a: Palette, b: Palette, t: number): Palette {
  const n = (x: number, y: number) => x + (y - x) * t
  return {
    skyTop: mixHex(a.skyTop, b.skyTop, t),
    skyBottom: mixHex(a.skyBottom, b.skyBottom, t),
    ground: mixHex(a.ground, b.ground, t),
    ground2: mixHex(a.ground2, b.ground2, t),
    sun: mixHex(a.sun, b.sun, t),
    sunIntensity: n(a.sunIntensity, b.sunIntensity),
    hemiSky: mixHex(a.hemiSky, b.hemiSky, t),
    hemiGround: mixHex(a.hemiGround, b.hemiGround, t),
    hemiIntensity: n(a.hemiIntensity, b.hemiIntensity),
    fogNear: n(a.fogNear, b.fogNear),
    fogFar: n(a.fogFar, b.fogFar),
    accent: mixHex(a.accent, b.accent, t),
  }
}

